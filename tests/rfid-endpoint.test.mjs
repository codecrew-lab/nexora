// RFID endpoint end-to-end test: firmware-shaped HTTP requests -> the real
// pulse-rfid-attendance edge function (Deno) -> a minimal PostgREST stand-in ->
// the real migrations on PGlite. Needs Deno on PATH (or DENO=/path/to/deno).
//   cd tests && npm install && npm run test:e2e
import http from 'node:http';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
import { PGlite } from '@electric-sql/pglite';

const repo = fileURLToPath(new URL('..', import.meta.url));
const db = new PGlite();
const q = async (sql, params) => (await db.query(sql, params)).rows;
await db.exec(`
  create role anon; create role authenticated; create role service_role;
  create schema auth;
  create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql as $$ select null::uuid $$;
  create function auth.jwt() returns jsonb language sql as $$ select '{}'::jsonb $$;
  create table public.students (id bigint generated by default as identity primary key,
    student_code text unique, student_name text, class_name text, auth_user_id uuid, created_at timestamptz default now());
  create function public.is_auraway_teacher() returns boolean language sql stable as $$ select false $$;
`);
await db.exec(fs.readFileSync(`${repo}/supabase/attendance-setup.sql`, 'utf8'));
await db.exec(fs.readFileSync(`${repo}/supabase/migrations/20261117180000_create_student_rfid_cards.sql`, 'utf8'));
await db.exec(fs.readFileSync(`${repo}/supabase/migrations/20261127120000_rfid_attendance_v2.sql`, 'utf8'));
await db.exec(`
  insert into public.students (student_code, student_name, class_name) values ('C8-001', 'Asha Rao', 'Class 8'), ('C8-002', 'Vikram Shah', 'Class 8');
  insert into public.student_rfid_cards (student_id, card_uid) values (1, '39C38E02'), (2, 'AABBCCDD');
`);

const SECRET = 'test-secret-0123456789abcdef0123456789';
let failures = 0;
const check = (name, cond, extra) => {
  if (cond) console.log('  ok   ', name);
  else { failures++; console.log('  FAIL ', name, JSON.stringify(extra)); }
};

// Minimal PostgREST stand-in: POST /rest/v1/rpc/<fn> with named JSON args.
const rest = http.createServer(async (req, res) => {
  const m = req.url.match(/^\/rest\/v1\/rpc\/(\w+)/);
  let raw = '';
  for await (const chunk of req) raw += chunk;
  const args = JSON.parse(raw || '{}');
  const names = Object.keys(args);
  const sql = `select public.${m[1]}(${names.map((n, i) => `${n} => $${i + 1}`).join(', ')}) as r`;
  try {
    const rows = await q(sql, names.map(n => args[n]));
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify(rows[0].r));
  } catch (e) {
    res.writeHead(400, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ code: e.code, message: e.message }));
  }
}).listen(54329);

const fn = spawn(process.env.DENO || 'deno', ['run', '--allow-net', '--allow-env', `${repo}/supabase/functions/pulse-rfid-attendance/index.ts`], {
  env: { ...process.env, SUPABASE_URL: 'http://127.0.0.1:54329', SUPABASE_SERVICE_ROLE_KEY: 'service-key', PULSE_RFID_DEVICE_SECRET: SECRET },
  stdio: ['ignore', 'pipe', 'pipe'],
});
fn.stderr.on('data', d => { if (!/Listening/.test(String(d))) process.stderr.write('[deno] ' + d); });
await new Promise(resolve => {
  const timer = setTimeout(resolve, 15000);
  const onData = d => { if (/Listening|8000/.test(String(d))) { clearTimeout(timer); resolve(); } };
  fn.stdout.on('data', onData);
  fn.stderr.on('data', onData);
});

const post = async (body, secret = SECRET, extraHeaders = {}) => {
  const res = await fetch('http://127.0.0.1:8000/', {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-pulse-device-secret': secret, ...extraHeaders },
    body: typeof body === 'string' ? body : JSON.stringify(body),
  });
  return { status: res.status, body: await res.json() };
};

try {
  const todayIst = (await q(`select (now() at time zone 'Asia/Kolkata')::date::text d`))[0].d;
  let r = await post({ card_uid: '39C38E02', device_id: 'Main Gate' });
  check('tap -> 200 present_marked with name', r.status === 200 && r.body.result === 'present_marked' && r.body.student_name === 'Asha Rao', r);
  r = await post({ card_uid: '39C38E02', device_id: 'main-gate' });
  check('repeat tap -> already_marked', r.status === 200 && r.body.result === 'already_marked', r);
  r = await post({ card_uid: 'DEADBEEF' });
  check('unknown card -> 200 unregistered_card (v1 returned 404)', r.status === 200 && r.body.result === 'unregistered_card' && r.body.card_uid === 'DEADBEEF', r);
  r = await post({ card_uid: '39C38E02' }, 'wrong-secret');
  check('wrong secret -> 401', r.status === 401 && r.body.result === 'error', r);
  r = await post({ card_uid: 'zz' });
  check('bad uid -> 400', r.status === 400, r);
  r = await post('not json');
  check('bad json -> 400', r.status === 400, r);
  const yesterday = Math.floor(Date.now() / 1000) - 86400;
  r = await post({ card_uid: 'AABBCCDD', device_id: 'main-gate', scanned_at: yesterday });
  check('offline replay (epoch seconds) -> yesterday', r.status === 200 && r.body.result === 'present_marked' && r.body.attendance_date < todayIst, r);
  r = await post({ card_uid: 'AABBCCDD', scanned_at: 12345 });
  check('unset device clock ignored -> server time (today)', r.status === 200 && r.body.result === 'present_marked' && r.body.attendance_date === todayIst, r);
  r = await post({ type: 'heartbeat', device_id: 'main-gate', firmware: '2.0.0', rssi: -58, queued: 2 });
  check('heartbeat -> ok', r.status === 200 && r.body.result === 'ok' && r.body.device_id === 'main-gate', r);
  r = await post({ card_uid: 'AABBCCDD' }, SECRET, { 'x-pulse-device-id': 'Library Door' });
  const libDoor = await q(`select 1 from rfid_devices where device_id = 'library-door'`);
  check('device id taken from header when body has none', r.status === 200 && libDoor.length === 1, r);
  const get = await fetch('http://127.0.0.1:8000/');
  check('GET -> 405', get.status === 405);
} finally {
  fn.kill();
  rest.close();
}
console.log(failures ? `\n${failures} FAILED` : '\nE2E PASSED');
process.exit(failures ? 1 : 0);
