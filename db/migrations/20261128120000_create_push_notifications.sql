-- NEXORA web push notifications (PWA).
--
-- 1. push_subscriptions stores one row per (device, role, student). Only the
--    server reads or writes it.
-- 2. Triggers on assignments, attendance_records and student_marks record each
--    change in push_outbox. The server (server/src/push.js) collects the outbox
--    every few seconds and notifies students and parents.
--
-- The outbox keeps notifications out of the teacher's transaction: a slow or
-- failed push can never delay or roll back a save.

begin;

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null check (endpoint like 'https://%' and length(endpoint) <= 1000),
  p256dh text not null check (length(p256dh) between 20 and 200),
  auth text not null check (length(auth) between 8 and 100),
  role text not null check (role in ('student', 'parent')),
  student_code text not null check (length(student_code) between 1 and 40),
  user_agent text check (user_agent is null or length(user_agent) <= 300),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (endpoint, role, student_code)
);

create index if not exists push_subscriptions_student_code_idx
  on public.push_subscriptions (student_code);

create table if not exists public.push_outbox (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record jsonb not null,
  created_at timestamptz not null default now()
);

-- RLS on with no policies and no grants: browsers can never read endpoints,
-- keys or queued changes directly.
alter table public.push_subscriptions enable row level security;
alter table public.push_outbox enable row level security;
revoke all on table public.push_subscriptions, public.push_outbox from public, anon, authenticated;

create or replace function public.nexora_push_notify()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  -- Attendance edits that keep the same status should not notify anyone.
  -- Nested on purpose: only attendance_records has a status column, and a
  -- single combined condition fails on the other tables.
  if tg_table_name = 'attendance_records' and tg_op = 'UPDATE' then
    if new.status is not distinct from old.status then
      return new;
    end if;
  end if;

  insert into public.push_outbox (table_name, record) values (tg_table_name, to_jsonb(new));
  return new;
exception when others then
  -- Never let a notification problem roll back the original insert/update.
  raise warning 'NEXORA push trigger failed: %', sqlerrm;
  return new;
end;
$$;

revoke all on function public.nexora_push_notify() from public, anon, authenticated;

drop trigger if exists nexora_push_new_assignment on public.assignments;
create trigger nexora_push_new_assignment
  after insert on public.assignments
  for each row execute function public.nexora_push_notify();

drop trigger if exists nexora_push_attendance on public.attendance_records;
create trigger nexora_push_attendance
  after insert or update of status on public.attendance_records
  for each row execute function public.nexora_push_notify();

drop trigger if exists nexora_push_new_marks on public.student_marks;
create trigger nexora_push_new_marks
  after insert on public.student_marks
  for each row execute function public.nexora_push_notify();

commit;
