create or replace function public.pulse_calendar_link_unassigned_students(p_student_ids bigint[])
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_school uuid;
  v_count integer;
begin
  if not public.is_auraway_teacher() then
    raise exception 'Only teachers can manage the school calendar.' using errcode = '42501';
  end if;
  select s.id into v_school from public.schools s order by s.created_at limit 1;
  if v_school is null then
    raise exception 'Set up the school calendar first.';
  end if;
  update public.students s set school_id = v_school
  where s.school_id is null and s.id = any(coalesce(p_student_ids, '{}'::bigint[]));
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

-- ---------------------------------------------------------------------------
-- 4. Sibling account links
-- ---------------------------------------------------------------------------
-- Two students are linked only after someone has signed in as both: student A
-- asks for the link, then signs in as student B to approve it. A link lets the
-- family switch accounts; switching still needs the other account's password.
create table if not exists public.student_sibling_links (
  id bigint generated by default as identity primary key,
  student_a_id bigint not null references public.students(id) on delete cascade,
  student_b_id bigint not null references public.students(id) on delete cascade,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint student_sibling_links_ordered check (student_a_id < student_b_id),
  unique (student_a_id, student_b_id)
);

create table if not exists public.student_sibling_link_requests (
  id uuid primary key default gen_random_uuid(),
  requester_student_id bigint not null references public.students(id) on delete cascade,
  target_student_id bigint not null references public.students(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'approved')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '15 minutes'
);

create index if not exists student_sibling_links_student_b_id_idx on public.student_sibling_links (student_b_id);
create index if not exists student_sibling_links_created_by_idx on public.student_sibling_links (created_by);
create index if not exists student_sibling_link_requests_requester_student_id_idx on public.student_sibling_link_requests (requester_student_id);
create index if not exists student_sibling_link_requests_target_student_id_idx on public.student_sibling_link_requests (target_student_id);

alter table public.student_sibling_links enable row level security;
alter table public.student_sibling_link_requests enable row level security;
revoke all on table public.student_sibling_links, public.student_sibling_link_requests from public, anon, authenticated;

create or replace function public.pulse_request_sibling_link(p_sibling_code text)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_me bigint;
  v_target bigint;
  v_request uuid;
begin
  select s.id into v_me from public.students s where s.auth_user_id = auth.uid();
  if v_me is null then
    raise exception 'Sign in with your student account first.';
  end if;
  select s.id into v_target from public.students s where s.student_code = upper(btrim(coalesce(p_sibling_code, '')));
  if v_target is null or v_target = v_me then
    raise exception 'Check the sibling code and try again.';
  end if;
  if exists (
    select 1 from public.student_sibling_links l
    where l.student_a_id = least(v_me, v_target) and l.student_b_id = greatest(v_me, v_target)
  ) then
    raise exception 'These accounts are already linked.';
  end if;

  delete from public.student_sibling_link_requests r
  where r.requester_student_id = v_me and (r.status = 'pending' or r.expires_at <= now());
  insert into public.student_sibling_link_requests (requester_student_id, target_student_id)
  values (v_me, v_target)
  returning id into v_request;
  return v_request;
end;
$$;

-- Called while signed in as the sibling, which proves the family knows that
-- account's password too.
create or replace function public.pulse_approve_sibling_link_request(p_request_id uuid)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_me bigint;
  v_request public.student_sibling_link_requests%rowtype;
begin
  select s.id into v_me from public.students s where s.auth_user_id = auth.uid();
  select * into v_request from public.student_sibling_link_requests r
  where r.id = p_request_id and r.status = 'pending' and r.expires_at > now()
  for update;
  if v_me is null or not found or v_request.target_student_id <> v_me then
    raise exception 'This link request is no longer valid. Please start again.';
  end if;

  insert into public.student_sibling_links (student_a_id, student_b_id, created_by)
  values (least(v_request.requester_student_id, v_me), greatest(v_request.requester_student_id, v_me), auth.uid())
  on conflict (student_a_id, student_b_id) do nothing;
  update public.student_sibling_link_requests r set status = 'approved' where r.id = v_request.id;
end;
$$;

create or replace function public.pulse_get_my_siblings()
returns table (student_id bigint, student_name text, class_name text)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select s.id, s.student_name, s.class_name
  from public.student_sibling_links l
  join public.students s
    on s.id = case when l.student_a_id = public.current_student_id() then l.student_b_id else l.student_a_id end
  where public.current_student_id() in (l.student_a_id, l.student_b_id)
  order by s.student_name;
$$;

create or replace function public.pulse_is_linked_sibling_code(p_student_code text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.students other
    join public.student_sibling_links l
      on l.student_a_id = least(other.id, public.current_student_id())
     and l.student_b_id = greatest(other.id, public.current_student_id())
    where other.student_code = upper(btrim(coalesce(p_student_code, '')))
  );
$$;

