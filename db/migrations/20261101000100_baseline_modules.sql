-- NEXORA baseline, part 2: exams, the daily quiz, the school calendar and
-- sibling account links.
--
-- The quiz and sibling tables are never exposed to browsers. Pages reach them
-- only through the pulse_* functions below, which check who is calling. That is
-- what keeps correct answers and other families' links private.

begin;

-- ---------------------------------------------------------------------------
-- 1. Teacher-assigned exams
-- ---------------------------------------------------------------------------
create table if not exists public.nexora_exams (
  id uuid primary key default gen_random_uuid(),
  title text not null check (length(btrim(title)) between 1 and 160),
  subject text not null check (length(btrim(subject)) between 1 and 80),
  instructions text not null default '' check (length(instructions) <= 4000),
  starts_at timestamptz not null,
  duration_minutes integer not null check (duration_minutes between 1 and 600),
  status text not null default 'published' check (status in ('draft', 'published', 'cancelled')),
  visibility text not null default 'assigned' check (visibility in ('assigned')),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_by_role text not null default 'teacher' check (created_by_role in ('teacher')),
  created_by_student_id bigint references public.students(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.nexora_exam_targets (
  id bigint generated by default as identity primary key,
  exam_id uuid not null references public.nexora_exams(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  assigned_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (exam_id, student_id)
);

create index if not exists nexora_exams_starts_at_idx on public.nexora_exams (starts_at);
create index if not exists nexora_exams_created_by_idx on public.nexora_exams (created_by);
create index if not exists nexora_exam_targets_student_idx on public.nexora_exam_targets (student_id);

alter table public.nexora_exams enable row level security;
alter table public.nexora_exam_targets enable row level security;
revoke all on table public.nexora_exams, public.nexora_exam_targets from public, anon;
grant select, insert, update, delete on table public.nexora_exams, public.nexora_exam_targets to authenticated;

drop policy if exists "Teachers manage exams" on public.nexora_exams;
create policy "Teachers manage exams"
  on public.nexora_exams for all to authenticated
  using ((select public.is_auraway_teacher()))
  with check ((select public.is_auraway_teacher()));

drop policy if exists "Students read exams assigned to them" on public.nexora_exams;
create policy "Students read exams assigned to them"
  on public.nexora_exams for select to authenticated
  using (
    status = 'published'
    and exists (
      select 1 from public.nexora_exam_targets t
      where t.exam_id = nexora_exams.id and t.student_id = (select public.current_student_id())
    )
  );

drop policy if exists "Teachers manage exam targets" on public.nexora_exam_targets;
create policy "Teachers manage exam targets"
  on public.nexora_exam_targets for all to authenticated
  using ((select public.is_auraway_teacher()))
  with check ((select public.is_auraway_teacher()));

drop policy if exists "Students read their own exam targets" on public.nexora_exam_targets;
create policy "Students read their own exam targets"
  on public.nexora_exam_targets for select to authenticated
  using (student_id = (select public.current_student_id()));

-- ---------------------------------------------------------------------------
-- 2. Daily quiz
-- ---------------------------------------------------------------------------
-- Ten random active questions per subject per day (IST) for Standards 5-12.
-- A student can leave and resume the same ten; one scored attempt per day.
create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  subject text not null check (subject in ('Mathematics', 'Science', 'English', 'Social Science', 'Malayalam', 'Computer Science')),
  question text not null check (length(btrim(question)) between 1 and 500),
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) = 4),
  correct_option smallint not null check (correct_option between 0 and 3),
  explanation text not null default '' check (length(explanation) <= 1000),
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists quiz_questions_subject_active_idx on public.quiz_questions (subject) where is_active;

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  subject text not null,
  quiz_date date not null,
  question_ids bigint[] not null,
  answers jsonb,
  score smallint,
  status text not null default 'in_progress' check (status in ('in_progress', 'completed')),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (student_id, subject, quiz_date)
);

alter table public.quiz_questions enable row level security;
alter table public.quiz_attempts enable row level security;
revoke all on table public.quiz_questions, public.quiz_attempts from public, anon, authenticated;

create or replace function public.pulse_begin_daily_quiz(p_subject text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_student public.students%rowtype;
  v_grade integer;
  v_today date := (now() at time zone 'Asia/Kolkata')::date;
  v_attempt public.quiz_attempts%rowtype;
  v_ids bigint[];
begin
  select * into v_student from public.students s where s.auth_user_id = auth.uid();
  if not found then
    raise exception 'Sign in with your student account to take the daily quiz.';
  end if;
  v_grade := substring(v_student.class_name from '(\d{1,2})')::integer;
  if v_grade is null or v_grade < 5 or v_grade > 12 then
    raise exception 'Daily quizzes are available only for Standards 5 to 12.';
  end if;
  if p_subject is null or p_subject not in ('Mathematics', 'Science', 'English', 'Social Science', 'Malayalam', 'Computer Science') then
    raise exception 'Unknown quiz subject.';
  end if;

  select * into v_attempt from public.quiz_attempts a
  where a.student_id = v_student.id and a.subject = p_subject and a.quiz_date = v_today;

  if not found then
    select array_agg(q.id) into v_ids
    from (select id from public.quiz_questions where subject = p_subject and is_active order by random() limit 10) q;
    if coalesce(cardinality(v_ids), 0) < 10 then
      raise exception 'Today''s % quiz is not ready yet. Ask your teacher to add more questions.', p_subject;
    end if;
    -- Two tabs starting at once must end up with the same ten questions.
    insert into public.quiz_attempts (student_id, subject, quiz_date, question_ids)
    values (v_student.id, p_subject, v_today, v_ids)
    on conflict (student_id, subject, quiz_date) do nothing;
    select * into v_attempt from public.quiz_attempts a
    where a.student_id = v_student.id and a.subject = p_subject and a.quiz_date = v_today;
  end if;

  if v_attempt.status = 'completed' then
    return jsonb_build_object('status', 'completed', 'score', v_attempt.score);
  end if;

  -- The correct option is never sent to the browser.
  return jsonb_build_object(
    'status', 'in_progress',
    'questions', (
      select coalesce(jsonb_agg(jsonb_build_object('id', q.id, 'question', q.question, 'options', q.options) order by t.position), '[]'::jsonb)
      from unnest(v_attempt.question_ids) with ordinality as t(id, position)
      join public.quiz_questions q on q.id = t.id
    )
  );
end;
$$;

create or replace function public.pulse_submit_daily_quiz(p_subject text, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_student_id bigint;
  v_today date := (now() at time zone 'Asia/Kolkata')::date;
  v_attempt public.quiz_attempts%rowtype;
  v_score integer;
begin
  select s.id into v_student_id from public.students s where s.auth_user_id = auth.uid();
  if v_student_id is null then
    raise exception 'Sign in with your student account to take the daily quiz.';
  end if;

  select * into v_attempt from public.quiz_attempts a
  where a.student_id = v_student_id and a.subject = p_subject and a.quiz_date = v_today
  for update;
  if not found then
    raise exception 'Start today''s quiz before submitting answers.';
  end if;
  if v_attempt.status = 'completed' then
    return jsonb_build_object('status', 'completed', 'score', v_attempt.score);
  end if;
  if p_answers is null or jsonb_typeof(p_answers) <> 'object' then
    raise exception 'Your answers are missing. Please try again.';
  end if;

  -- Answers are { "<question id>": <option index 0-3> }.
  select count(*) into v_score
  from unnest(v_attempt.question_ids) as t(id)
  join public.quiz_questions q on q.id = t.id
  where (p_answers ->> t.id::text) ~ '^[0-3]$'
    and (p_answers ->> t.id::text)::smallint = q.correct_option;

  update public.quiz_attempts a
  set status = 'completed',
      score = v_score,
      answers = (select jsonb_object_agg(t.id::text, p_answers -> t.id::text) from unnest(v_attempt.question_ids) as t(id)),
      completed_at = now()
  where a.id = v_attempt.id;

  return jsonb_build_object('status', 'completed', 'score', v_score);
end;
$$;

create or replace function public.pulse_teacher_list_quiz_questions(p_subject text default null)
returns table (
  id bigint, subject text, question text, options jsonb, correct_option smallint,
  explanation text, is_active boolean, updated_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.is_auraway_teacher() then
    raise exception 'Only teachers can manage quiz questions.' using errcode = '42501';
  end if;
  return query
    select q.id, q.subject, q.question, q.options, q.correct_option, q.explanation, q.is_active, q.updated_at
    from public.quiz_questions q
    where coalesce(p_subject, '') = '' or q.subject = p_subject
    order by q.subject, q.id desc;
end;
$$;

create or replace function public.pulse_teacher_save_quiz_question(
  p_id bigint,
  p_subject text,
  p_question text,
  p_options text[],
  p_correct_option integer,
  p_explanation text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
  v_options text[];
begin
  if not public.is_auraway_teacher() then
    raise exception 'Only teachers can manage quiz questions.' using errcode = '42501';
  end if;
  select array_agg(btrim(option) order by position) into v_options
  from unnest(p_options) with ordinality as o(option, position);
  if coalesce(cardinality(v_options), 0) <> 4
     or exists (select 1 from unnest(v_options) as o(option) where o.option is null or o.option = '' or length(o.option) > 200) then
    raise exception 'A question needs four options of up to 200 characters each.';
  end if;
  if p_correct_option is null or p_correct_option not between 0 and 3 then
    raise exception 'Choose which of the four options is correct.';
  end if;

  if p_id is null then
    insert into public.quiz_questions (subject, question, options, correct_option, explanation, created_by)
    values (p_subject, btrim(p_question), to_jsonb(v_options), p_correct_option, coalesce(btrim(p_explanation), ''), auth.uid())
    returning quiz_questions.id into v_id;
  else
    update public.quiz_questions q
    set subject = p_subject,
        question = btrim(p_question),
        options = to_jsonb(v_options),
        correct_option = p_correct_option,
        explanation = coalesce(btrim(p_explanation), ''),
        updated_at = now()
    where q.id = p_id
    returning q.id into v_id;
    if v_id is null then
      raise exception 'That question no longer exists.';
    end if;
  end if;
  return v_id;
end;
$$;

