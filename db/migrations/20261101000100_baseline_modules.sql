-- The caller's school and whether they may edit its calendar. No rows means
-- "not linked to a school yet".
create or replace function public.pulse_calendar_my_context()
returns table (school_id uuid, school_name text, can_manage boolean)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if public.is_auraway_teacher() then
    return query select s.id, s.name, true from public.schools s order by s.created_at limit 1;
  else
    return query
      select s.id, s.name, false
      from public.students st join public.schools s on s.id = st.school_id
      where st.auth_user_id = auth.uid();
  end if;
end;
$$;

create or replace function public.pulse_calendar_create_school(p_name text)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id uuid;
begin
  if not public.is_auraway_teacher() then
    raise exception 'Only teachers can set up the school calendar.' using errcode = '42501';
  end if;
  if length(btrim(coalesce(p_name, ''))) not between 2 and 120 then
    raise exception 'Enter the school name (2 to 120 characters).';
  end if;
  -- One school per installation; serialise two teachers pressing the button together.
  lock table public.schools in share row exclusive mode;
  if exists (select 1 from public.schools) then
    raise exception 'The school calendar has already been set up.';
  end if;
  insert into public.schools (name, created_by) values (btrim(p_name), auth.uid()) returning id into v_id;
  -- Everyone already registered joins it; later students join on creation.
  update public.students set school_id = v_id where school_id is null;
  return v_id;
end;
$$;

