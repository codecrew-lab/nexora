-- NEXORA baseline, part 1: the teacher account, students, assignments, student
-- updates and attendance.
--
-- Run db/platform.sql first (npm run db:setup does both). Everything a browser
-- can reach is protected by row-level security:
--   * teachers (public.is_auraway_teacher()) manage everything;
--   * a student reads only rows that belong to their own student record;
--   * parents have no account and go through the server's parent-report.

begin;

-- ---------------------------------------------------------------------------
-- 1. Who is a teacher
-- ---------------------------------------------------------------------------
-- The claims come from the token the server signed at sign-in, built from
-- auth.users. Users cannot edit them.
create or replace function public.is_auraway_teacher()
returns boolean
language sql
stable
set search_path = public, pg_temp
as $$
  select coalesce(
    auth.role() = 'authenticated'
    and (
      lower(auth.jwt() ->> 'email') = 'teacher@auraway.app'
      or (auth.jwt() -> 'app_metadata' ->> 'role') in ('teacher', 'school_admin')
    ),
    false
  );
$$;

-- The shared teacher identity that the code sign-in uses (docs/teacher-login.md).
-- It has no password: the only way in is the two codes held by the server.
insert into auth.users (email, email_confirmed_at, raw_app_meta_data, raw_user_meta_data)
select 'teacher@auraway.app', now(), '{"role": "teacher"}'::jsonb, '{"display_name": "Teacher"}'::jsonb
where not exists (select 1 from auth.users where lower(email) = 'teacher@auraway.app');

-- ---------------------------------------------------------------------------
-- 2. Schools and students
-- ---------------------------------------------------------------------------
create table if not exists public.schools (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 2 and 120),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  -- The code is the student's login name and the parents' lookup key.
  student_code text not null unique check (student_code ~ '^[A-Z0-9-]{4,40}$'),
  student_name text not null check (length(btrim(student_name)) between 1 and 120),
  class_name text not null check (length(btrim(class_name)) between 1 and 60),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  school_id uuid references public.schools(id) on delete set null,
  study_hours text check (study_hours is null or length(study_hours) <= 120),
  attendance_pct text check (attendance_pct is null or length(attendance_pct) <= 40),
  teacher_request text check (teacher_request is null or length(teacher_request) <= 500),
  areas_to_improve text check (areas_to_improve is null or length(areas_to_improve) <= 500),
  created_at timestamptz not null default now()
);

create index if not exists students_school_id_idx on public.students (school_id);
create index if not exists students_class_name_idx on public.students (class_name);

-- The signed-in student's own record. SECURITY DEFINER so policies on other
-- tables can ask "is this row mine?" without needing to read public.students.
create or replace function public.current_student_id()
returns bigint
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select s.id from public.students s where s.auth_user_id = auth.uid();
$$;

create or replace function public.current_student_code()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select s.student_code from public.students s where s.auth_user_id = auth.uid();
$$;

create or replace function public.current_student_class()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select s.class_name from public.students s where s.auth_user_id = auth.uid();
$$;

create or replace function public.current_student_school_id()
returns uuid
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select s.school_id from public.students s where s.auth_user_id = auth.uid();
$$;

revoke all on function public.current_student_id(), public.current_student_code(),
  public.current_student_class(), public.current_student_school_id() from public;
grant execute on function public.current_student_id(), public.current_student_code(),
  public.current_student_class(), public.current_student_school_id() to authenticated;

-- Codes are stored upper-case. While the school has exactly one calendar
-- (public.schools row), new students join it automatically.
create or replace function public.students_before_insert()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  new.student_code := upper(btrim(new.student_code));
  if new.school_id is null and (select count(*) from public.schools) = 1 then
    select s.id into new.school_id from public.schools s;
  end if;
  return new;
end;
$$;

drop trigger if exists students_before_insert on public.students;
create trigger students_before_insert
  before insert on public.students
  for each row execute function public.students_before_insert();

-- Deleting a student also deletes their login, so a removed student cannot
-- keep signing in. Only ever removes a student account.
create or replace function public.students_after_delete()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if old.auth_user_id is not null then
    delete from auth.users u
    where u.id = old.auth_user_id and u.raw_app_meta_data ->> 'role' = 'student';
  end if;
  return old;
end;
$$;

drop trigger if exists students_after_delete on public.students;
create trigger students_after_delete
  after delete on public.students
  for each row execute function public.students_after_delete();

revoke all on function public.students_before_insert(), public.students_after_delete() from public;

alter table public.schools enable row level security;
revoke all on table public.schools from public, anon;
grant select on table public.schools to authenticated;

drop policy if exists "Teachers and members read their school" on public.schools;
create policy "Teachers and members read their school"
  on public.schools for select to authenticated
  using ((select public.is_auraway_teacher()) or id = (select public.current_student_school_id()));

alter table public.students enable row level security;
revoke all on table public.students from public, anon;
grant select, insert, update, delete on table public.students to authenticated;

drop policy if exists "Teachers manage students" on public.students;
create policy "Teachers manage students"
  on public.students for all to authenticated
  using ((select public.is_auraway_teacher()))
  with check ((select public.is_auraway_teacher()));

drop policy if exists "Students read their own profile" on public.students;
create policy "Students read their own profile"
  on public.students for select to authenticated
  using (auth_user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- 3. Assignments
-- ---------------------------------------------------------------------------
-- target_code is 'ALL', one student's code, or 'CLASS:<class name>'.
create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  title text not null check (length(btrim(title)) between 1 and 200),
  subject text not null default '' check (length(subject) <= 80),
  due_date date,
  target_code text not null default 'ALL' check (length(target_code) between 1 and 80),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists assignments_due_date_idx on public.assignments (due_date);
create index if not exists assignments_created_by_idx on public.assignments (created_by);

alter table public.assignments enable row level security;
revoke all on table public.assignments from public, anon;
grant select, insert, update, delete on table public.assignments to authenticated;

drop policy if exists "Teachers manage assignments" on public.assignments;
create policy "Teachers manage assignments"
  on public.assignments for all to authenticated
  using ((select public.is_auraway_teacher()))
  with check ((select public.is_auraway_teacher()));

drop policy if exists "Students read assignments set for them" on public.assignments;
create policy "Students read assignments set for them"
  on public.assignments for select to authenticated
  using (
    (select public.current_student_id()) is not null
    and (
      target_code = 'ALL'
      or target_code = (select public.current_student_code())
      or target_code = 'CLASS:' || (select public.current_student_class())
    )
  );

-- ---------------------------------------------------------------------------
-- 4. Student updates (homework status and notes to the teacher)
-- ---------------------------------------------------------------------------
-- Append-only: the newest row per assignment and student is the current status.
create table if not exists public.student_updates (
  id bigint generated by default as identity primary key,
  student_code text not null,
  student_name text check (student_name is null or length(student_name) <= 120),
  assignment_id bigint references public.assignments(id) on delete cascade,
  assignment_title text check (assignment_title is null or length(assignment_title) <= 200),
  status text not null check (status in ('Completed', 'Not Completed', 'Student Note')),
  student_note text check (student_note is null or length(student_note) <= 2000),
  updated_at timestamptz not null default now()
);

create index if not exists student_updates_student_idx on public.student_updates (student_code, updated_at desc);
create index if not exists student_updates_assignment_idx on public.student_updates (assignment_id);

alter table public.student_updates enable row level security;
revoke all on table public.student_updates from public, anon;
grant select, insert, delete on table public.student_updates to authenticated;

drop policy if exists "Teachers and owners read student updates" on public.student_updates;
create policy "Teachers and owners read student updates"
  on public.student_updates for select to authenticated
  using ((select public.is_auraway_teacher()) or student_code = (select public.current_student_code()));

-- A student can only post as themselves.
drop policy if exists "Students post their own updates" on public.student_updates;
create policy "Students post their own updates"
  on public.student_updates for insert to authenticated
  with check ((select public.is_auraway_teacher()) or student_code = (select public.current_student_code()));

-- Who may delete updates is set in 20261120150000 (school administrators only).

-- ---------------------------------------------------------------------------
-- 5. Attendance
-- ---------------------------------------------------------------------------
-- One row per student per day. RFID columns are added in 20261127120000.
create table if not exists public.attendance_records (
  id bigint generated by default as identity primary key,
  student_code text not null,
  attendance_date date not null,
  status text not null check (status in ('Present', 'Absent', 'Leave')),
  marked_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  unique (student_code, attendance_date)
);

create index if not exists attendance_records_date_idx on public.attendance_records (attendance_date);

alter table public.attendance_records enable row level security;
revoke all on table public.attendance_records from public, anon;
grant select, insert, update, delete on table public.attendance_records to authenticated;

drop policy if exists "Teachers manage attendance records" on public.attendance_records;
create policy "Teachers manage attendance records"
  on public.attendance_records for all to authenticated
  using ((select public.is_auraway_teacher()))
  with check ((select public.is_auraway_teacher()));

drop policy if exists "Students read their own attendance" on public.attendance_records;
create policy "Students read their own attendance"
  on public.attendance_records for select to authenticated
  using (student_code = (select public.current_student_code()));

commit;
