-- NEXORA web push notifications (PWA).
--
-- 1. push_subscriptions stores one row per (device, role, student). Only the
--    push-notify edge function (service role) reads or writes it.
-- 2. Triggers on assignments, attendance_records and student_marks call the
--    push-notify edge function through pg_net so students and parents are
--    notified automatically.
--
-- Before running this file, store the webhook secret in Vault (same value as the
-- PUSH_WEBHOOK_SECRET edge function secret):
--   select vault.create_secret('<PUSH_WEBHOOK_SECRET>', 'nexora_push_webhook_secret');

create extension if not exists pg_net;

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null check (endpoint like 'https://%' and length(endpoint) <= 1000),
  p256dh text not null check (length(p256dh) between 20 and 200),
  auth text not null check (length(auth) between 8 and 100),
  role text not null check (role in ('student', 'parent')),
  student_code text not null check (length(student_code) between 1 and 40),
  user_agent text check (user_agent is null or length(user_agent) <= 300),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (endpoint, role, student_code)
);

create index if not exists push_subscriptions_student_code_idx
  on public.push_subscriptions (student_code);

-- RLS on with no policies: browsers can never read endpoints or keys directly.
alter table public.push_subscriptions enable row level security;
revoke all on public.push_subscriptions from anon, authenticated;

-- Sends table changes to the push-notify edge function.
create or replace function public.nexora_push_notify()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  webhook_secret text;
begin
  -- Attendance edits that keep the same status should not notify anyone.
  if tg_op = 'UPDATE' and tg_table_name = 'attendance_records'
     and new.status is not distinct from old.status then
    return new;
  end if;

  select decrypted_secret into webhook_secret
  from vault.decrypted_secrets
  where name = 'nexora_push_webhook_secret'
  limit 1;

  if webhook_secret is null then
    raise warning 'NEXORA push: vault secret nexora_push_webhook_secret is missing';
    return new;
  end if;

  -- pg_net is asynchronous: a slow or failed push never blocks the teacher's save.
  perform net.http_post(
    url := 'https://iazlemocpuhzwtrkyfgw.supabase.co/functions/v1/push-notify',
    body := jsonb_build_object(
      'action', 'event',
      'table', tg_table_name,
      'op', tg_op,
      'record', to_jsonb(new)
    ),
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-nexora-push-secret', webhook_secret
    ),
    timeout_milliseconds := 5000
  );
  return new;
exception when others then
  -- Never let a notification problem roll back the original insert/update.
  raise warning 'NEXORA push trigger failed: %', sqlerrm;
  return new;
end;
$$;

revoke all on function public.nexora_push_notify() from public, anon, authenticated;

drop trigger if exists nexora_push_new_assignment on public.assignments;
create trigger nexora_push_new_assignment
  after insert on public.assignments
  for each row execute function public.nexora_push_notify();

drop trigger if exists nexora_push_attendance on public.attendance_records;
create trigger nexora_push_attendance
  after insert or update of status on public.attendance_records
  for each row execute function public.nexora_push_notify();

drop trigger if exists nexora_push_new_marks on public.student_marks;
create trigger nexora_push_new_marks
  after insert on public.student_marks
  for each row execute function public.nexora_push_notify();
