-- PULSE RFID card registry. Card UIDs are identifiers, not secure credentials.
create table if not exists public.student_rfid_cards (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete restrict,
  card_uid text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint student_rfid_cards_uid_format check (card_uid ~ '^[0-9A-F]{8,20}$')
);

create unique index if not exists student_rfid_cards_one_active_per_student
  on public.student_rfid_cards(student_id) where active = true;

create index if not exists student_rfid_cards_student_id_idx
  on public.student_rfid_cards(student_id);

alter table public.student_rfid_cards enable row level security;
revoke all on table public.student_rfid_cards from anon, public;
grant select, insert, update, delete on table public.student_rfid_cards to authenticated;
grant usage, select on sequence public.student_rfid_cards_id_seq to authenticated;

drop policy if exists "Teachers manage student RFID cards" on public.student_rfid_cards;
create policy "Teachers manage student RFID cards"
  on public.student_rfid_cards
  for all
  to authenticated
  using ((select public.is_auraway_teacher()))
  with check ((select public.is_auraway_teacher()));
